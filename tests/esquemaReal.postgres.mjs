async function exportar(db) {
  const resultado = {}
  for (const [clave, sql] of Object.entries(consultas)) {
    const filas = (await db.query(sql)).rows
    assert.deepEqual(Object.keys(filas[0]), ['ddl'], `${clave} devuelve una sola columna`)
    assert.match(filas[0].ddl, new RegExp(`^-- ${clave}: \\d+ (sentencias|buckets)`), `${clave} empieza con la cantidad`)
    assert.equal(filas.at(-1).ddl, `-- fin ${clave}`, `${clave} termina con la marca de fin`)
    resultado[clave] = filas.map(f => f.ddl)
  }
  return resultado
}

// Orden para rearmar: tipos → tablas → índices → funciones → vistas → triggers → políticas → permisos.
const ORDEN = ['e1', 'e2', 'e3', 'e5', 'e4', 'e6', 'e7a', 'e7b', 'e8']

// e7b trae los buckets como JSON (una fila por bucket); acá se convierten en el INSERT equivalente.
const bucketsComoSql = lineas => lineas.map(l => {
  if (l.startsWith('--')) return l
  const b = JSON.parse(l)
  const lit = v => v === null ? 'NULL' : "'" + String(v).replaceAll("'", "''") + "'"
  const tipos = b.allowed_mime_types === null ? 'NULL' : 'ARRAY[' + b.allowed_mime_types.map(lit).join(', ') + ']::text[]'
  return `INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (${lit(b.id)}, ${lit(b.name)}, ${b.public}, ${b.file_size_limit ?? 'NULL'}, ${tipos}) ON CONFLICT (id) DO UPDATE SET public = EXCLUDED.public, file_size_limit = EXCLUDED.file_size_limit, allowed_mime_types = EXCLUDED.allowed_mime_types;`
})
// Las consultas se corren con el search_path del editor de Supabase: lo de public sale sin prefijo.
const armarScript = exp => 'SET check_function_bodies = off;\nSET search_path = public;\n' +ORDEN.map(c => (c === 'e7b' ? bucketsComoSql(exp[c]) : exp[c]).join('\n')).join('\n')

test('Esquema real: las consultas exportan todo sin datos y el resultado rearma una base idéntica', async () => {
  const original = new PGlite()
  const copia = new PGlite()
  try {
    await original.exec(BASE_SUPABASE + EJEMPLO)
    const exp = await exportar(original)
    const todo = Object.values(exp).flat().join('\n')

    // Sin datos: ni emails ni filas.
    assert.doesNotMatch(todo, /persona@club\.test|'Primera'/)
    // Lo propio sí, lo de Supabase no.
    for (const esperado of [/CREATE SCHEMA IF NOT EXISTS seguridad_privado/, /CREATE TYPE public\.rol_usuario AS ENUM/, /CREATE DOMAIN public\.puntaje/,
      /GENERATED ALWAYS AS IDENTITY/, /GENERATED ALWAYS AS \(\(\(nombre \|\| ' '::text\) \|\| apellido\)\) STORED/, /FOREIGN KEY \(categoria_id\) REFERENCES categorias\(id\) ON DELETE RESTRICT/, /^\{"id" : "Biblioteca", "name" : "Biblioteca", "public" : true, "file_size_limit" : 5242880, "allowed_mime_types" : \["image\/\*"\]\}$/m,
      /WHERE \(estado = 'disponible'::text\)/, /WITH \(security_invoker=true\)/, /CREATE MATERIALIZED VIEW/, /SECURITY DEFINER/, /CREATE OR REPLACE PROCEDURE public\.limpiar/,
      /CREATE TRIGGER jugadores_tocar/, /AS RESTRICTIVE FOR UPDATE TO PUBLIC/, /"Biblioteca subir segun rol" ON storage\.objects/,
      /GRANT SELECT \(nombre\) ON TABLE public\.jugadores TO anon/, /GRANT EXECUTE ON ROUTINE public\.mi_rol\(\) TO authenticated WITH GRANT OPTION/,
      /ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT .* ON TABLES TO authenticated/, /FORCE ROW LEVEL SECURITY/, /COMMENT ON COLUMN public\.jugadores\.estado/,
      /ALTER SEQUENCE public\.contador_id_seq OWNED BY public\.contador\.id/]) {
      assert.match(todo, esperado)
    }
    assert.doesNotMatch(todo, /CREATE TABLE storage\.|CREATE (OR REPLACE )?FUNCTION auth\.|CREATE SCHEMA IF NOT EXISTS (auth|storage)\b/)
    assert.match(exp.e1[0], /omitidos: auth, information_schema, storage$/)

    // Rearmar en una base vacía y volver a exportar: tiene que dar lo mismo.
    await copia.exec(BASE_SUPABASE)
    await copia.exec(armarScript(exp))
    const exp2 = await exportar(copia)
    for (const clave of Object.keys(exp)) assert.deepEqual(exp2[clave], exp[clave], clave)
  } finally {
    await original.close()
    await copia.close()
  }
})

test('Generador: CSV con comillas y saltos de línea, control de cortes, datos sensibles y UUID', () => {
  assert.deepEqual(leerCsv('ddl\r\n"a, ""b""\nc"\r\nd\n'), [['ddl'], ['a, "b"\nc'], ['d']])
  const csv = filas => 'ddl\n' + filas.map(f => '"' + f.replaceAll('"', '""') + '"').join('\n') + '\n'
  assert.deepEqual(leerSeccion('e3', csv(['-- e3: 1 sentencias', 'CREATE INDEX x ON t (a);', '-- fin e3'])).cuerpo, ['CREATE INDEX x ON t (a);'])
  assert.throws(() => leerSeccion('e3', csv(['-- e3: 2 sentencias', 'CREATE INDEX x ON t (a);', '-- fin e3'])), /dice 2 y hay 1/)
  assert.throws(() => leerSeccion('e3', csv(['-- e3: 1 sentencias', 'CREATE INDEX x ON t (a);'])), /cortado/)
  assert.deepEqual(buscarSensibles("select 'ana@ejemplo.invalid'; -- eyJhbGciOiJIUzI1NiJ9.eyJyb2xlIjoiYW5vbiJ9.x"), ['email: ana@ejemplo.invalid', 'token JWT: eyJhbGciOiJIUzI1NiJ9.eyJyb2xlIjoiYW5vbiJ9'])
  assert.deepEqual(buscarSensibles("COMMENT ON TABLE t IS 'https://datafem.com.ar/primera-b'; gen_random_uuid()"), [])
  const { salida, cantidad } = ocultarUuids("IN ('1A2B3C4D-1111-4222-8333-ABCDEF012345'::uuid, '1a2b3c4d-1111-4222-8333-abcdef012345', '5e6f7a8b-4444-4555-8666-0123456789ab')")
  assert.equal(cantidad, 2)
  assert.equal(salida, "IN ('00000000-0000-4000-8000-000000000001'::uuid, '00000000-0000-4000-8000-000000000001', '00000000-0000-4000-8000-000000000002')")

  // Un CSV con un email no puede terminar en el archivo.
  const fuentes = Object.fromEntries(SECCIONES.map(([c]) => [c, csv([`-- ${c}: 0 ${c === 'e7b' ? 'buckets' : 'sentencias'}`, `-- fin ${c}`])]))
  fuentes.e5 = csv(['-- e5: 1 sentencias', "CREATE FUNCTION f() RETURNS text LANGUAGE sql AS $$ select 'ana@ejemplo.invalid' $$;", '-- fin e5'])
  assert.deepEqual(armar(c => fuentes[c], '2026-01-01').sensibles, ['email: ana@ejemplo.invalid'])
})

test('esquema_real.sql versionado: sin datos sensibles y se carga completo en una base vacía', async () => {
  const sql = readFileSync(new URL('../supabase/esquema/esquema_real.sql', import.meta.url), 'utf8')
  assert.deepEqual(buscarSensibles(sql), [])
  assert.doesNotMatch(sql.replace(/00000000-0000-4000-8000-\d{12}/g, ''), /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i)
  const db = new PGlite()
  try {
    // Lo de Supabase que el esquema usa pero no exporta. Las extensiones de Supabase no existen en PGlite.
    await db.exec(`
      create role anon; create role authenticated; create role service_role; create role supabase_admin;
      create schema auth; create schema extensions; create schema storage;
      create table auth.users (id uuid primary key, email text, banned_until timestamptz);
      create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
      create function auth.role() returns text language sql stable as $$ select null::text $$;
      create function auth.jwt() returns jsonb language sql stable as $$ select '{}'::jsonb $$;
      create table storage.buckets (id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
      create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text, name text);
      alter table storage.objects enable row level security;`)
    // La base real es PostgreSQL 17 (permiso MAINTAIN); PGlite es 16 y no lo conoce.
    const paraPglite = sql.split('\n').filter(l => !l.startsWith('CREATE EXTENSION')).join('\n').replaceAll(' MAINTAIN,', '')
    await db.exec(paraPglite)
    const n = async q => (await db.query(q)).rows[0].n
    assert.equal(await n(`select count(*)::int as n from pg_tables where schemaname not in ('pg_catalog', 'information_schema', 'auth', 'storage')`), (sql.match(/^CREATE TABLE /gm) || []).length)
    assert.equal(await n(`select count(*)::int as n from pg_policies`), (sql.match(/^CREATE POLICY /gm) || []).length)
    assert.equal(await n(`select count(*)::int as n from pg_trigger where not tgisinternal`), (sql.match(/^CREATE TRIGGER /gm) || []).length)
  } finally { await db.close() }
})
